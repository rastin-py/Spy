// Generates lib/design/tokens.g.dart from tokens.json.
//
//   dart run tool/gen_tokens.dart
//
// tokens.json is the single source. Nothing below invents a value; it only
// changes the shape. If you need a new value, add it to tokens.json and re-run.
import 'dart:convert';
import 'dart:io';

void main() {
  final json =
      jsonDecode(File('tokens.json').readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer();

  out.writeln('// GENERATED BY tool/gen_tokens.dart FROM tokens.json - DO NOT EDIT.');
  out.writeln('//');
  out.writeln('// Two layers. [SpyPrimitives] holds the raw ramps and scales and is read by');
  out.writeln('// the theme alone. [SpyColors] holds the semantic aliases and is the only');
  out.writeln('// colour surface a widget may touch, delivered as a ThemeExtension.');
  out.writeln("import 'dart:ui' show Color, Offset;");
  out.writeln("import 'package:flutter/foundation.dart' show immutable;");
  out.writeln("import 'package:flutter/material.dart' show BoxShadow, Cubic, ThemeExtension;");
  out.writeln();

  // ---------------------------------------------------------------- primitives
  out.writeln('/// Raw values. Widgets never read these - see [SpyColors].');
  out.writeln('abstract final class SpyPrimitives {');
  final colors = json['color'] as Map<String, dynamic>;
  for (final ramp in colors.entries) {
    out.writeln('  // ${ramp.key}');
    final shades = ramp.value as Map<String, dynamic>;
    for (final shade in shades.entries) {
      final name = '${ramp.key}${shade.key}';
      out.writeln('  static const $name = ${dartColor(shade.value[r'$value'] as String)};');
    }
  }
  out.writeln();
  out.writeln('  /// The redaction bar. The darkest thing on the phone, in both themes.');
  out.writeln('  static const ink = neutral0;');
  out.writeln();
  out.writeln('  // space - 4pt scale');
  for (final e in (json['space'] as Map<String, dynamic>).entries) {
    out.writeln('  static const s${e.key} = ${px(e.value[r'$value'] as String)};');
  }
  out.writeln();
  out.writeln('  // radius - small and hard');
  for (final e in (json['radius'] as Map<String, dynamic>).entries) {
    out.writeln('  static const r${cap(e.key)} = ${px(e.value[r'$value'] as String)};');
  }
  out.writeln();
  out.writeln('  // motion');
  for (final e in (json['motion']['duration'] as Map<String, dynamic>).entries) {
    final ms = (e.value[r'$value'] as String).replaceAll('ms', '');
    out.writeln('  static const d${cap(e.key)} = Duration(milliseconds: $ms);');
  }
  for (final e in (json['motion']['easing'] as Map<String, dynamic>).entries) {
    final v = (e.value[r'$value'] as List).map((n) => (n as num).toDouble()).toList();
    out.writeln('  static const e${cap(e.key)} = Cubic(${v.join(', ')});');
  }
  out.writeln();
  out.writeln('  // type scale');
  for (final e in (json['font']['size'] as Map<String, dynamic>).entries) {
    out.writeln('  static const fs${cap(e.key)} = ${px(e.value[r'$value'] as String)};');
  }
  for (final e in (json['font']['family'] as Map<String, dynamic>).entries) {
    out.writeln("  static const ff${cap(e.key)} = '${e.value[r'$value']}';");
  }
  out.writeln();
  out.writeln('  // layout - phone only');
  final layout = json['layout'] as Map<String, dynamic>;
  out.writeln('  static const bpCompact = ${px(layout['breakpoint']['compact'][r'$value'] as String)};');
  out.writeln('  static const bpWide = ${px(layout['breakpoint']['wide'][r'$value'] as String)};');
  out.writeln('  static const tapMin = ${px(layout['tapMin'][r'$value'] as String)};');
  out.writeln('  static const contentMax = ${px(layout['contentMax'][r'$value'] as String)};');
  out.writeln('}');
  out.writeln();

  // ------------------------------------------------------------------ semantic
  final noir = json['theme']['noir'] as Map<String, dynamic>;
  final daylight = json['theme']['daylight'] as Map<String, dynamic>;
  if (noir.keys.join() != daylight.keys.join()) {
    stderr.writeln('noir and daylight must declare identical keys');
    exit(1);
  }
  final fields = noir.keys
      .map((k) => (name: camel(k), token: k, type: noir[k][r'$type'] as String))
      .toList();

  out.writeln('/// The semantic layer - every colour a widget is allowed to read.');
  out.writeln('///');
  out.writeln('///     final c = context.spy;');
  out.writeln('///     ColoredBox(color: c.surface);   // yes');
  out.writeln('///     ColoredBox(color: Colors.grey); // no - fails review');
  out.writeln('@immutable');
  out.writeln('final class SpyColors extends ThemeExtension<SpyColors> {');
  for (final f in fields) {
    out.writeln('  final ${dartType(f.type)} ${f.name};');
  }
  out.writeln();
  out.writeln('  const SpyColors({');
  for (final f in fields) {
    out.writeln('    required this.${f.name},');
  }
  out.writeln('  });');
  out.writeln();
  out.writeln('  /// Low light, not low contrast.');
  emitTheme(out, 'noir', noir, fields, colors);
  out.writeln();
  out.writeln('  /// The case file on the desk. Not a degraded mode.');
  emitTheme(out, 'daylight', daylight, fields, colors);
  out.writeln();
  out.writeln('  @override');
  out.writeln('  SpyColors copyWith() => this;');
  out.writeln();
  out.writeln('  @override');
  out.writeln('  SpyColors lerp(SpyColors? other, double t) {');
  out.writeln('    if (other == null) return this;');
  out.writeln('    return SpyColors(');
  for (final f in fields) {
    out.writeln('      ${f.name}: ${lerpExpr(f.type, f.name)},');
  }
  out.writeln('    );');
  out.writeln('  }');
  out.writeln('}');

  File('lib/design/tokens.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('lib/design/tokens.g.dart - ${fields.length} semantic aliases, '
      '${colors.values.fold<int>(0, (a, r) => a + (r as Map).length)} primitives');
}

void emitTheme(
  StringBuffer out,
  String name,
  Map<String, dynamic> theme,
  List<({String name, String token, String type})> fields,
  Map<String, dynamic> colors,
) {
  out.writeln('  static const $name = SpyColors(');
  for (final f in fields) {
    out.writeln('    ${f.name}: ${value(theme[f.token] as Map<String, dynamic>, colors)},');
  }
  out.writeln('  );');
}

String value(Map<String, dynamic> token, Map<String, dynamic> colors) {
  final v = token[r'$value'];
  switch (token[r'$type']) {
    case 'color':
      return dartColor(resolve(v as String, colors));
    case 'number':
      final d = (v as num).toDouble();
      return d == d.roundToDouble() ? d.toStringAsFixed(1) : '$d';
    case 'shadow':
      final s = v as Map<String, dynamic>;
      final color = dartColor(resolve(s['color'] as String, colors));
      final dx = px(s['offsetX'] as String);
      final dy = px(s['offsetY'] as String);
      return 'BoxShadow(color: $color, offset: Offset($dx, $dy), '
          'blurRadius: ${px(s['blur'] as String)}, '
          'spreadRadius: ${px(s['spread'] as String)})';
    default:
      throw StateError('unhandled token type ${token[r'$type']}');
  }
}

/// `{color.brass.400}` -> `#DFA83C`. Literal hex passes through untouched.
String resolve(String raw, Map<String, dynamic> colors) {
  if (!raw.startsWith('{')) return raw;
  final path = raw.substring(1, raw.length - 1).split('.');
  dynamic node = <String, dynamic>{'color': colors};
  for (final part in path) {
    node = node[part];
    if (node == null) throw StateError('unresolved token reference $raw');
  }
  return node[r'$value'] as String;
}

String dartType(String tokenType) => switch (tokenType) {
      'color' => 'Color',
      'number' => 'double',
      'shadow' => 'BoxShadow',
      _ => throw StateError('unhandled token type $tokenType'),
    };

String lerpExpr(String tokenType, String field) => switch (tokenType) {
      'color' => 'Color.lerp($field, other.$field, t)!',
      'number' => '$field + (other.$field - $field) * t',
      'shadow' => 'BoxShadow.lerp($field, other.$field, t)!',
      _ => throw StateError('unhandled token type $tokenType'),
    };

/// `#DFA83C` / `#030406D1` -> `Color(0xFFDFA83C)` (alpha defaults to opaque).
String dartColor(String hex) {
  final h = hex.replaceFirst('#', '').toUpperCase();
  return switch (h.length) {
    6 => 'Color(0xFF$h)',
    8 => 'Color(0x${h.substring(6)}${h.substring(0, 6)})', // RRGGBBAA -> AARRGGBB
    _ => throw StateError('not a hex colour: $hex'),
  };
}

String px(String v) {
  final d = double.parse(v.replaceAll('px', ''));
  return d == d.roundToDouble() ? d.toStringAsFixed(1) : '$d';
}

String cap(String s) => s[0].toUpperCase() + s.substring(1);

/// `surface-raised` -> `surfaceRaised`
String camel(String s) {
  final parts = s.split('-');
  return parts.first + parts.skip(1).map(cap).join();
}
